function buildMaterial(seed: MaterialSeed): SemiconductorMaterial {
  const parsed = parseChemicalFormula(seed.formula);
  if (!parsed) {
    throw new Error(`Invalid formula in seed ${seed.id}: ${seed.formula}`);
  }

  const elements: TrimElementConfig[] = parsed.map((p) => {
    const sc = getElementByZ(p.z);
    const pt = getPTableElement(p.z);
    const ov = seed.thresholdOverrides?.[p.symbol];
    return {
      z: p.z,
      symbol: sc.symbol,
      name: sc.name,
      stoich: p.stoich,
      massAmu: sc.naturalWeight,
      displacementEv: ov?.ed ?? pt?.defaultEd ?? 20.0,
      latticeBindingEv: ov?.eb ?? pt?.defaultEb ?? 2.5,
      surfaceBindingEv: ov?.es ?? pt?.defaultEs ?? sc.heatSubl ?? 2.5,
    };
  });

  return {
    id: seed.id,
    name: seed.name,
    formula: seed.formula,
    category: seed.category,
    densityGPerCm3: seed.densityGPerCm3,
    densityRange: seed.densityRange,
    phase: 0,
    compoundCorr: seed.compoundCorr ?? 1.0,
    processNote: seed.processNote,
    elements,
  };
}

export const SEMICONDUCTOR_MATERIALS: SemiconductorMaterial[] = MATERIAL_SEEDS.map(buildMaterial);
